export function filterCatalogSeeds(
  query: string = "",
  category?: string,
): Edition[] {
  const q = query.trim().toLowerCase();
  return CATALOG_SEEDS.filter((edition) => {
    if (category && category !== "all" && edition.category !== category)
      return false;
    if (!q) return true;
    const searchable = `${edition.brand} ${edition.name} ${edition.flavor ?? ""} ${edition.line ?? ""} ${edition.design ?? ""} ${edition.barcodes.join(" ")}`.toLowerCase();
    return searchable.includes(q);
  });
}
